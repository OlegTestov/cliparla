/**
 * Save and restore the user's clipboard around a paste, and build image items,
 * using the asynchronous ClipboardItem API (Electron 44+).
 */

type Content = Blob | string

export interface ClipboardItemLike {
  readonly types: readonly string[]
  getType(type: string): Promise<unknown>
}

export type ClipboardItemCtor<T extends ClipboardItemLike = ClipboardItemLike> = new (
  items: Record<string, Content>
) => T

export interface ClipboardLike {
  read(): Promise<ClipboardItemLike[]>
  write(items: never[]): Promise<void>
  /** Empties the clipboard */
  clear?(): void | Promise<void>
}

/** One clipboard entry: MIME type -> its content. */
export type SavedItem = Record<string, Content>

/** Real formats only: macOS reports an empty pasteboard as one item of "electron application/findtext". */
export const isMimeType = (type: string): boolean => /^[a-z]+\/[\w.+-]+$/i.test(type)

/**
 * Formats only the source app understands (Figma, Excel...) are listed as the pseudo-type
 * `electron application/osclipboard;format="<name>"`. Electron writes that type back as the raw
 * format, and one write can carry many of them next to text, so they are saved like MIME types.
 * The text pseudo-type is already carried by text/plain.
 */
const OS_CLIPBOARD = /^electron application\/osclipboard;format="(.+)"$/
const TEXT_FORMATS = new Set(['NSStringPboardType'])
export const isPrivateFormat = (type: string): boolean => {
  const name = OS_CLIPBOARD.exec(type)?.[1]
  return name !== undefined && !TEXT_FORMATS.has(name)
}
/** nspasteboard.org markers are empty on purpose: they must come back, or a history app records the secret. */
const MARKERS = ['ConcealedType', 'TransientType', 'AutoGeneratedType'].map(
  (name) => `org.nspasteboard.${name}`
)
export const isMarkerFormat = (type: string): boolean => {
  const name = OS_CLIPBOARD.exec(type)?.[1]
  return name !== undefined && MARKERS.includes(name)
}
const isRestorable = (type: string): boolean => isMimeType(type) || isPrivateFormat(type)

/** How long the clipboard may be read before a paste. See `saveClipboard`. */
export const CLIPBOARD_READ_TIMEOUT_MS = 300

export interface SaveOptions {
  timeoutMs?: number
  /** Called once when the time ran out and the clipboard is only partly saved */
  onTimeout?: () => void
}

/** Electron resolves a raw format it cannot read as an empty Blob instead of rejecting. */
const isEmptyBlob = (value: unknown): boolean => value instanceof Blob && value.size === 0

/**
 * Read everything on the clipboard. An empty clipboard is `[]` (it is emptied again after the
 * paste); one that cannot be read is `null` (left exactly as it is afterwards). An empty private
 * format counts as unreadable, except the nspasteboard.org markers. An item whose marker could not
 * be read is dropped, so its secret never comes back unmarked.
 *
 * The reads run before the paste keystroke, so they are bounded in total (300 ms by default: the
 * paste already waits up to 400 ms for focus, and a normal read takes a few milliseconds, so more
 * than 300 ms means a slow source app, and a late paste is worse than a partly restored
 * clipboard). All formats are read at once; when time runs out the formats read so far are kept,
 * the result is a copy that later reads cannot change, and `onTimeout` is called. Nothing read: `null`.
 */
export async function saveClipboard(
  clipboard: Pick<ClipboardLike, 'read'>,
  options: SaveOptions = {}
): Promise<SavedItem[] | null> {
  const saved: SavedItem[] = []
  const sources: ClipboardItemLike[] = []
  let hadTypes = false
  const work = (async () => {
    const items = await clipboard.read()
    hadTypes = items.some((item) => item.types.some(isRestorable))
    // Every format of every item is read at once, so one that never arrives holds back no other
    await Promise.all(
      items.map(async (item) => {
        const entry: SavedItem = {}
        saved.push(entry)
        sources.push(item)
        await Promise.all(
          item.types.filter(isRestorable).map(async (type) => {
            try {
              const value = await item.getType(type)
              if (isPrivateFormat(type) && !isMarkerFormat(type) && isEmptyBlob(value)) return
              entry[type] = value as Content
            } catch {
              // one unreadable format must not drop the readable ones
            }
          })
        )
      })
    )
  })()

  let timer: ReturnType<typeof setTimeout> | undefined
  const outcome = await Promise.race([
    work.then(
      () => 'done' as const,
      () => 'failed' as const
    ),
    new Promise<'timeout'>((resolve) => {
      timer = setTimeout(() => resolve('timeout'), options.timeoutMs ?? CLIPBOARD_READ_TIMEOUT_MS)
    })
  ])
  clearTimeout(timer)
  if (outcome === 'failed') return null
  for (const [index, item] of sources.entries()) {
    if (item.types.some((type) => isMarkerFormat(type) && !(type in saved[index])))
      saved[index] = {}
  }
  if (outcome === 'timeout') {
    options.onTimeout?.()
    const snapshot = saved.map((entry) => ({ ...entry }))
    return snapshot.some((entry) => Object.keys(entry).length > 0) ? snapshot : null
  }
  // Formats existed but none could be read: same as an unreadable clipboard
  if (hadTypes && saved.every((entry) => Object.keys(entry).length === 0)) return null
  return saved
}

const COMMON_TYPES = ['text/plain', 'text/html', 'image/png']

const lines = (text: string): string[] => text.split(/\r?\n/).filter((line) => line !== '')

/**
 * A copied file is a uri-list, and the system also offers its lines as plain text. Writing both
 * back makes the system put the list on the clipboard twice, so the plain text is left to the list.
 */
async function withoutDuplicateUriList(entry: SavedItem): Promise<SavedItem> {
  const uris = entry['text/uri-list']
  const plain = entry['text/plain']
  if (uris === undefined || plain === undefined) return entry
  // Electron's getType resolves Blobs
  const [uriText, plainText] = await Promise.all([contentText(uris), contentText(plain)])
  if (lines(uriText).join('\n') !== lines(plainText).join('\n')) return entry
  const { 'text/plain': _plain, ...rest } = entry
  void _plain
  return rest
}

/** Raw image formats Electron lists next to its own image/png rendering of the same picture. */
const RAW_IMAGE =
  /^electron application\/osclipboard;format="(Apple PNG|NeXT TIFF v4\.0) pasteboard type"$/

/**
 * Writing image/png next to the raw image format makes macOS add a second item with a re-encoded
 * PNG (and an extra TIFF), so the raw format alone is written back.
 */
function withoutDerivedPng(entry: SavedItem): SavedItem {
  if (!('image/png' in entry) || !Object.keys(entry).some((type) => RAW_IMAGE.test(type)))
    return entry
  const { 'image/png': _png, ...rest } = entry
  void _png
  return rest
}

const contentText = async (content: Content): Promise<string> =>
  typeof content === 'string' ? content : content.text()

/**
 * Put saved items back. An empty clipboard is emptied again; one that could not be read is left
 * alone. If the platform refuses some format, the formats it does accept are restored (first the
 * common text/HTML/PNG ones, then plain text only) instead of nothing; when even that fails it throws
 * and the clipboard keeps the dictated text rather than being emptied.
 */
export async function restoreClipboard(
  clipboard: { write(items: never[]): Promise<void>; clear?(): void | Promise<void> },
  Item: ClipboardItemCtor,
  saved: SavedItem[] | null
): Promise<'exact' | 'partial' | 'untouched'> {
  if (saved === null) return 'untouched'
  if (saved.every((entry) => Object.keys(entry).length === 0)) {
    if (clipboard.clear) await clipboard.clear()
    else await clipboard.write([])
    return 'exact'
  }

  const exact = (await Promise.all(saved.map(withoutDuplicateUriList))).map(withoutDerivedPng)
  // A marked secret is never written back in a reduced form that would lose its marker
  const unmarked = (entry: SavedItem): boolean => !Object.keys(entry).some(isMarkerFormat)
  const attempts: SavedItem[][] = [
    exact,
    saved.filter(unmarked).map((entry) => pick(entry, COMMON_TYPES)),
    saved.filter(unmarked).map((entry) => pick(entry, ['text/plain']))
  ]
  let lastError: unknown
  for (const [index, attempt] of attempts.entries()) {
    const items = attempt.filter((entry) => Object.keys(entry).length > 0)
    if (items.length === 0) continue
    try {
      await clipboard.write(items.map((entry) => new Item(entry)) as never[])
      return index === 0 ? 'exact' : 'partial'
    } catch (error) {
      lastError = error
    }
  }
  throw lastError ?? new Error('Nothing could be restored')
}

function pick(entry: SavedItem, types: string[]): SavedItem {
  return Object.fromEntries(Object.entries(entry).filter(([type]) => types.includes(type)))
}

/** A clipboard item holding PNG bytes. */
export function pngItem<T extends ClipboardItemLike>(Item: ClipboardItemCtor<T>, png: Buffer): T {
  return new Item({ 'image/png': new Blob([new Uint8Array(png)], { type: 'image/png' }) })
}
