// Writes THIRD_PARTY_NOTICES.md: name, version, license and license text of every runtime dependency
// (the closure of package.json "dependencies" found in node_modules). Electron/Chromium notices ship inside the app.
import { readFileSync, writeFileSync, existsSync, readdirSync } from 'node:fs'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const readJson = (p) => JSON.parse(readFileSync(p, 'utf8'))
const rootPkg = readJson(join(root, 'package.json'))

function locate(name, fromDir) {
  let dir = fromDir
  for (;;) {
    const p = join(dir, 'node_modules', name, 'package.json')
    if (existsSync(p)) return dirname(p)
    const parent = dirname(dir)
    if (parent === dir || !parent.startsWith(root)) break
    dir = parent
  }
  const top = join(root, 'node_modules', name)
  return existsSync(join(top, 'package.json')) ? top : null
}

const seen = new Map()
function visit(name, fromDir) {
  const dir = locate(name, fromDir)
  if (!dir || seen.has(dir)) return
  const pkg = readJson(join(dir, 'package.json'))
  seen.set(dir, pkg)
  for (const dep of Object.keys({ ...pkg.dependencies, ...pkg.optionalDependencies }))
    visit(dep, dir)
}
for (const dep of Object.keys(rootPkg.dependencies ?? {})) visit(dep, root)

const licenseOf = (p) =>
  typeof p.license === 'string' ? p.license : (p.license?.type ?? 'see package')
const entries = [...seen.entries()].sort((a, b) => a[1].name.localeCompare(b[1].name))
const out = [
  '# Third-party notices',
  '',
  'Cliparla is MIT licensed (see LICENSE). It bundles the packages below. Electron and Chromium license texts are',
  'shipped inside the app (LICENSE, LICENSES.chromium.html). Generated by `npm run notices`; do not edit by hand.',
  ''
]
for (const [dir, p] of entries) {
  const file = readdirSync(dir).find((f) => /^(licen[sc]e|copying)/i.test(f))
  const text = file
    ? readFileSync(join(dir, file), 'utf8').trim()
    : `(no license file in the package; package.json declares ${licenseOf(p)})`
  out.push(`## ${p.name} ${p.version}`, '', `License: ${licenseOf(p)}`, '', '```', text, '```', '')
}
writeFileSync(join(root, 'THIRD_PARTY_NOTICES.md'), out.join('\n'))
console.log(`THIRD_PARTY_NOTICES.md: ${entries.length} packages`)
